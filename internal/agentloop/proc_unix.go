//go:build !windows

package agentloop

import (
	"os/exec"
	"syscall"
)

// setProcessGroup puts a command in its own process group and, when it is
// stopped, stops the whole group: a test runner's children die with it.
func setProcessGroup(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error { return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL) }
}
